#!/usr/bin/env bash
#
# Check that stage_source() in .github/scripts/ext-rpm.sh makes the Rust vendor
# tarball a spec names as "Source1: %{name}-%{version}-vendor.tar.xz" (spec
# style guide, "Rust vendoring"): a tarball with a top-level vendor/ directory,
# the same for the same commit, and a clear error without a Cargo.lock.
#
# Requires: bash, git, cargo, rpmdevtools (spectool), tar, xz (run it in
# ci-fedora or a Fedora container). The test crate has no dependencies, so it
# runs offline.
#
# Usage: tests/fedora-rust-vendor.sh [path/to/voulage]

set -euo pipefail

REPO="$(realpath "${1:-$(dirname "$0")/..}")"

# keep the user's git configuration out of the fixtures
export GIT_CONFIG_NOSYSTEM=1
export HOME
HOME="$(mktemp -d)"

failures=0
fail() {
  echo "FAIL: $*"
  failures=$((failures + 1))
}

# shellcheck source=SCRIPTDIR/../.github/scripts/ext-rpm.sh
source "$REPO/.github/scripts/ext-rpm.sh"
set +e

PKG_BUILD_PATH="$(mktemp -d)"
PACKAGE_NAME="regolith-hello-rs"
SRC="$PKG_BUILD_PATH/$PACKAGE_NAME"
VENDOR="$PKG_BUILD_PATH/.rpm/$PACKAGE_NAME/SOURCES/$PACKAGE_NAME-0.1.0-vendor.tar.xz"
trap 'rm -rf "$PKG_BUILD_PATH" "$HOME"' EXIT

# make_package <extra source line>: a Rust package repo with one commit
make_package() {
  rm -rf "$SRC"
  mkdir -p "$SRC/src"
  cat > "$SRC/Cargo.toml" <<EOF
[package]
name = "$PACKAGE_NAME"
version = "0.1.0"
edition = "2021"
EOF
  cat > "$SRC/Cargo.lock" <<EOF
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 3

[[package]]
name = "$PACKAGE_NAME"
version = "0.1.0"
EOF
  echo 'fn main() { println!("hello"); }' > "$SRC/src/main.rs"
  cat > "$SRC/$PACKAGE_NAME.spec" <<EOF
Name:           $PACKAGE_NAME
Version:        0.1.0
Release:        1%{?dist}
Summary:        test
License:        GPL-3.0-only
Source0:        %{name}-%{version}.tar.gz
$1

%description
test
EOF
  git -C "$SRC" init -q
  git -C "$SRC" add .
  GIT_COMMITTER_DATE="2026-11-03T18:00:00Z" GIT_AUTHOR_DATE="2026-11-03T18:00:00Z" \
    git -C "$SRC" -c user.name=test -c user.email=test@example.com commit -q -m init
  RPM_SPEC="$SRC/$PACKAGE_NAME.spec"
}

# the vendor tarball is made, with vendor/ at the top
make_package 'Source1:        %{name}-%{version}-vendor.tar.xz'
if ! out="$(stage_source 2>&1)"; then
  fail "stage_source failed: $out"
elif [ ! -f "$VENDOR" ]; then
  fail "no $(basename "$VENDOR") in SOURCES"
elif ! tar -tJf "$VENDOR" | grep -qx 'vendor/'; then
  fail "$(basename "$VENDOR") has no top-level vendor/ directory: $(tar -tJf "$VENDOR" | head -n3)"
elif tar -tJf "$VENDOR" | grep -qv '^vendor/'; then
  fail "$(basename "$VENDOR") has entries outside vendor/"
fi

# the same commit gives the same tarball
first="$(sha256sum "$VENDOR" 2>/dev/null | cut -d' ' -f1)"
stage_source >/dev/null 2>&1
if [ "$(sha256sum "$VENDOR" 2>/dev/null | cut -d' ' -f1)" != "$first" ]; then
  fail "a second stage_source made a different $(basename "$VENDOR")"
fi

# the source tree is left alone
if [ -e "$SRC/vendor" ] || [ -n "$(git -C "$SRC" status --porcelain)" ]; then
  fail "stage_source changed the package's tree: $(git -C "$SRC" status --porcelain)"
fi

# without a Cargo.lock it fails and says why
make_package 'Source1:        %{name}-%{version}-vendor.tar.xz'
git -C "$SRC" rm -q Cargo.lock
git -C "$SRC" -c user.name=test -c user.email=test@example.com commit -q -m "drop lock"
if out="$(stage_source 2>&1)"; then
  fail "stage_source succeeded without a Cargo.lock"
elif ! grep -q 'Cargo.lock' <<<"$out"; then
  fail "the error without a Cargo.lock doesn't mention it: $out"
fi

# other missing sources still fail as before
make_package 'Source1:        missing-file.tar.xz'
if out="$(stage_source 2>&1)"; then
  fail "stage_source succeeded with a missing Source1"
elif ! grep -q 'neither in the repo nor a URL' <<<"$out"; then
  fail "unexpected error for a missing Source1: $out"
fi

if [ "$failures" -gt 0 ]; then
  echo "$failures failure(s)"
  exit 1
fi
echo "OK: Rust vendor tarball"
